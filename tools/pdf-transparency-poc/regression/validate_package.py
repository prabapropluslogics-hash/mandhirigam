"""Package-level validation of packed PNG pages.

Historical mode: bit-for-bit integrity against the frozen catalog manifest.
Fresh mode: existence, format, self-consistent catalog/fingerprint from the
actual generated bytes — never gated on historical PNG SHA or byte totals.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image

from .fixture import (
    CATALOG_FINGERPRINT,
    OUTPUT_HEIGHT,
    OUTPUT_WIDTH,
    SOURCE_PAGE_COUNT,
)
from .paths import HarnessPaths
from .result import CheckResult, ReferenceRegressionResult
from .validate_source import sha256_file


def catalog_fingerprint(page_sha256s: list[str]) -> str:
    joined = "".join(page_sha256s).encode("ascii")
    return hashlib.sha256(joined).hexdigest()


def _historical_page_map(paths: HarnessPaths) -> dict[int, dict]:
    """Load expected page bytes/SHA only in historical integrity mode."""
    if paths.is_fresh:
        return {}
    manifest_path = paths.historical_manifest or paths.package_manifest
    if manifest_path is None or not manifest_path.is_file():
        return {}
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    return {int(entry["page"]): entry for entry in manifest.get("pages") or []}


def _write_fresh_catalog_manifest(
    path: Path,
    *,
    digests: list[str],
    page_bytes: list[int],
    fingerprint: str,
    total_bytes: int,
) -> dict:
    pages = []
    for index, (digest, size) in enumerate(zip(digests, page_bytes), start=1):
        pages.append(
            {
                "page": index,
                "source": f"page_{index:02d}/packed.png",
                "filename": f"page_{index:02d}.png",
                "width": OUTPUT_WIDTH,
                "height": OUTPUT_HEIGHT,
                "bytes": size,
                "sha256": digest,
            }
        )
    payload = {
        "description": (
            "Fresh Phase 2 processor catalog. SHA-256 and bytes are computed "
            "from the packed.png files in this output directory."
        ),
        "page_count": SOURCE_PAGE_COUNT,
        "width": OUTPUT_WIDTH,
        "height": OUTPUT_HEIGHT,
        "total_bytes": total_bytes,
        "fingerprint_sha256": fingerprint,
        "pages": pages,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return payload


def validate_package(
    result: ReferenceRegressionResult,
    paths: HarnessPaths | None = None,
) -> None:
    paths = paths or HarnessPaths.historical()
    result.mode = paths.mode
    result.add(
        CheckResult(
            "output_dir_exists",
            paths.output_dir.is_dir(),
            detail=str(paths.output_dir),
        )
    )

    historical = _historical_page_map(paths)

    if not paths.is_fresh and paths.package_manifest is not None:
        result.add(
            CheckResult(
                "package_manifest_exists",
                paths.package_manifest.is_file(),
                detail=str(paths.package_manifest),
            )
        )
        if paths.package_manifest.is_file():
            manifest = json.loads(paths.package_manifest.read_text(encoding="utf-8"))
            result.add(
                CheckResult(
                    "manifest_page_count",
                    manifest.get("page_count") == SOURCE_PAGE_COUNT,
                    detail=str(manifest.get("page_count")),
                )
            )
            result.add(
                CheckResult(
                    "manifest_dimensions",
                    manifest.get("width") == OUTPUT_WIDTH
                    and manifest.get("height") == OUTPUT_HEIGHT,
                    detail=f"{manifest.get('width')}x{manifest.get('height')}",
                )
            )
    elif paths.is_fresh:
        result.add(
            CheckResult(
                "fresh_mode_no_historical_sha_gate",
                True,
                detail=(
                    "fresh packed.png SHA/bytes are computed from generated "
                    "files; historical catalog SHA/totals are not required"
                ),
            )
        )

    seen_pages: set[int] = set()
    seen_hashes: set[str] = set()
    digests: list[str] = []
    page_bytes: list[int] = []
    total_bytes = 0

    for page in range(1, SOURCE_PAGE_COUNT + 1):
        path = paths.packed_png(page)
        exists = path.is_file()
        result.add(
            CheckResult(
                f"page_{page:02d}_exists",
                exists,
                detail=str(path),
            )
        )
        if not exists:
            continue
        seen_pages.add(page)

        size = path.stat().st_size
        total_bytes += size
        page_bytes.append(size)

        if paths.is_fresh:
            nonempty_ok = size > 0
            nonempty_detail = f"bytes={size}"
        else:
            expected_bytes = historical.get(page, {}).get("bytes")
            nonempty_ok = size > 0 and (
                expected_bytes is None or size == int(expected_bytes)
            )
            nonempty_detail = f"bytes={size} historical={expected_bytes}"
        result.add(
            CheckResult(
                f"page_{page:02d}_nonempty",
                nonempty_ok,
                detail=nonempty_detail,
            )
        )

        with Image.open(path) as image:
            mode = image.mode
            width, height = image.size
            extrema = image.getextrema() if mode == "RGBA" else None
        has_alpha = (
            mode == "RGBA"
            and extrema is not None
            and extrema[3][0] == 0
            and extrema[3][1] == 255
        )
        result.add(
            CheckResult(
                f"page_{page:02d}_rgba",
                mode == "RGBA" and has_alpha,
                detail=f"mode={mode} alpha={None if extrema is None else extrema[3]}",
            )
        )
        result.add(
            CheckResult(
                f"page_{page:02d}_dimensions",
                width == OUTPUT_WIDTH and height == OUTPUT_HEIGHT,
                detail=f"{width}x{height}",
            )
        )

        digest = sha256_file(path)
        digests.append(digest)
        result.page_sha256s[page] = digest

        if paths.is_fresh:
            sha_ok = len(digest) == 64 and digest not in seen_hashes
            sha_detail = digest
        else:
            expected_sha = str(historical.get(page, {}).get("sha256") or "").lower()
            matches_historical = (not expected_sha) or digest == expected_sha
            sha_ok = (
                len(digest) == 64
                and digest not in seen_hashes
                and matches_historical
            )
            sha_detail = (
                digest
                if matches_historical
                else f"fresh={digest} historical={expected_sha}"
            )
        result.add(
            CheckResult(
                f"page_{page:02d}_sha256",
                sha_ok,
                detail=sha_detail,
            )
        )
        seen_hashes.add(digest)

    missing = [
        page
        for page in range(1, SOURCE_PAGE_COUNT + 1)
        if page not in seen_pages
    ]
    result.add(
        CheckResult(
            "all_pages_present",
            not missing and len(seen_pages) == SOURCE_PAGE_COUNT,
            detail="ok" if not missing else f"missing={missing}",
        )
    )

    fingerprint = catalog_fingerprint(digests) if len(digests) == SOURCE_PAGE_COUNT else ""
    result.catalog_fingerprint = fingerprint
    result.total_output_bytes = total_bytes

    if paths.is_fresh:
        result.add(
            CheckResult(
                "fresh_catalog_fingerprint",
                len(fingerprint) == 64,
                detail=fingerprint or "(incomplete)",
            )
        )
        result.add(
            CheckResult(
                "fresh_total_bytes",
                total_bytes > 0 and len(page_bytes) == SOURCE_PAGE_COUNT,
                detail=str(total_bytes),
            )
        )
        if paths.package_manifest is not None and len(digests) == SOURCE_PAGE_COUNT:
            written = _write_fresh_catalog_manifest(
                paths.package_manifest,
                digests=digests,
                page_bytes=page_bytes,
                fingerprint=fingerprint,
                total_bytes=total_bytes,
            )
            result.add(
                CheckResult(
                    "fresh_catalog_manifest_written",
                    paths.package_manifest.is_file(),
                    detail=str(paths.package_manifest),
                )
            )
            reloaded = json.loads(paths.package_manifest.read_text(encoding="utf-8"))
            result.add(
                CheckResult(
                    "fresh_manifest_page_count",
                    reloaded.get("page_count") == SOURCE_PAGE_COUNT,
                    detail=str(reloaded.get("page_count")),
                )
            )
            result.add(
                CheckResult(
                    "fresh_manifest_dimensions",
                    reloaded.get("width") == OUTPUT_WIDTH
                    and reloaded.get("height") == OUTPUT_HEIGHT,
                    detail=f"{reloaded.get('width')}x{reloaded.get('height')}",
                )
            )
            result.add(
                CheckResult(
                    "fresh_manifest_fingerprint",
                    reloaded.get("fingerprint_sha256") == fingerprint,
                    detail=str(reloaded.get("fingerprint_sha256")),
                )
            )
            result.add(
                CheckResult(
                    "fresh_manifest_total_bytes",
                    int(reloaded.get("total_bytes") or -1) == total_bytes,
                    detail=f"total={total_bytes} manifest={reloaded.get('total_bytes')}",
                )
            )
            mismatch = []
            for entry in reloaded.get("pages") or []:
                page = int(entry["page"])
                actual = result.page_sha256s.get(page)
                if entry.get("sha256") != actual:
                    mismatch.append(page)
                if int(entry.get("bytes") or -1) != Path(
                    paths.packed_png(page)
                ).stat().st_size:
                    mismatch.append(page)
            result.add(
                CheckResult(
                    "fresh_manifest_entries_match_files",
                    not mismatch and len(reloaded.get("pages") or []) == SOURCE_PAGE_COUNT,
                    detail="ok" if not mismatch else f"mismatch_pages={sorted(set(mismatch))}",
                )
            )
            # Keep written payload referenced for reporting.
            _ = written
    else:
        result.add(
            CheckResult(
                "catalog_fingerprint",
                fingerprint == CATALOG_FINGERPRINT,
                detail=fingerprint or "(incomplete)",
            )
        )
        if paths.package_manifest is not None and paths.package_manifest.is_file():
            manifest = json.loads(paths.package_manifest.read_text(encoding="utf-8"))
            result.add(
                CheckResult(
                    "manifest_total_bytes",
                    total_bytes == int(manifest.get("total_bytes") or -1),
                    detail=f"total={total_bytes} manifest={manifest.get('total_bytes')}",
                )
            )
        elif historical:
            expected_total = sum(
                int(entry.get("bytes") or 0) for entry in historical.values()
            )
            result.add(
                CheckResult(
                    "historical_total_bytes",
                    total_bytes == expected_total,
                    detail=f"total={total_bytes} historical={expected_total}",
                )
            )
